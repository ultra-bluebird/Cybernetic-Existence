function test_validate_latency_records()
% Synthetic records; not reanalysis of any published system.
% Attribution:
% bostrom18sd2ujv24ual9c9pshtxys6j8knh6xaead9ye7

% Valid: source-supported decoder latency with explicit endpoints.
lorachStudy = struct("authors","Lorach et al.","year",2023, ...
    "journal","Nature","title","Walking naturally after SCI...");

r(1) = makeRecord( ...
    lorachStudy,"final_published_article", ...
    "Adaptive online calibration of the BSI", ...
    "verbatim_supplied", ...
    "latency of the decoder was as low as 1.1 s ...", ...
    "decoder_latency","primary_reported_measurement", ...
    "seven-state proportional control","online", ...
    "external_computer", ...
    "Feature window ready","explicit_in_source", ...
    "Decoder output available","explicit_in_source", ...
    "fully_defined","as_low_as","sem",1.1,"s", ...
    "exact wall-clock instrumentation not reported", ...
    "Cannot be summed with adjustment latency");

% Invalid: increment cannot be a primary-measured latency.
r(2) = makeRecord( ...
    lorachStudy,"final_published_article", ...
    "Abstract","verbatim_supplied", ...
    "80-ms increments","decoder_output_increment", ...
    "primary_reported_measurement", ...
    "attempted speech","online","external_computer", ...
    "Attempt","partially_defined","First audio","not_reported", ...
    "partially_defined","mean","none_reported",0.080,"s", ...
    "no explicit end event in the abstract","Do not treat as latency");
r(2).endpointStatus = "partially_defined";

% Valid: schedule (interval, not latency).
r(3) = makeRecord( ...
    lorachStudy,"final_published_article", ...
    "Adaptive online calibration of the BSI","verbatim_supplied", ...
    "updated commands were delivered every 300 ms", ...
    "command_update_interval","primary_reported_schedule", ...
    "seven-state walking","online","external_computer", ...
    "Not applicable","not_applicable", ...
    "Not applicable","not_applicable", ...
    "fully_defined","scheduled_value","none_reported", ...
    0.300,"s", ...
    "not a latency; acknowledgment timing unreported", ...
    "Interval, not loop latency");

% Invalid: ramp rate cannot be classified as latency.
r(4) = makeRecord( ...
    lorachStudy,"final_published_article", ...
    "Methods","verbatim_supplied", ...
    "ramp rate 1 mA/s","ramp_rate","primary_reported_measurement", ...
    "not applicable","not_applicable","embedded_in_device", ...
    "Not applicable","not_applicable", ...
    "Not applicable","not_applicable", ...
    "fully_defined","parameter_setting","none_reported", ...
    1.0,"mA_per_s","transition duration not reported", ...
    "ramp rate is not a latency");

% Valid: dwell duration (not response delay).
r(5) = makeRecord( ...
    lorachStudy,"final_published_article", ...
    "Results: Secondary outcomes","verbatim_supplied", ...
    "high-amplitude state 1.2 h","stimulation_state_dwell_duration", ...
    "primary_reported_measurement", ...
    "chronic use","not_applicable","embedded_in_device", ...
    "Enter high-amplitude state","explicit_in_source", ...
    "Exit high-amplitude state","explicit_in_source", ...
    "fully_defined","mean","plus_minus_unspecified",1.2,"h", ...
    "dispersion label must be verified per passage", ...
    "Dwell duration, not physiological response delay");

% Invalid: analyst calculation with undefined endpoints.
r(6) = makeRecord( ...
    lorachStudy,"final_published_article", ...
    "analyst summary","paraphrase_supplied","1.1 + 0.1", ...
    "decoder_latency","analyst_calculation", ...
    "combined","unreported","unreported", ...
    "Unknown","not_reported","Unknown","not_reported", ...
    "partially_defined","mean","none_reported",1.2,"s", ...
    "no matched endpoint evidence","Must not be reported as measured total");

report = validate_latency_records(r);

assert(report.recordCount == 6);
assert(report.validCount == 3);
assert(report.invalidCount == 3);

assert(report.validity(1));
assert(~report.validity(2));
assert(any(contains(report.reasons(2),"increment")));

assert(report.validity(3));
assert(~report.validity(4));
assert(any(contains(report.reasons(4),"ramp_rate")));

assert(report.validity(5));
assert(~report.validity(6));
assert(any(contains(report.reasons(6),"analyst_calculation")));

assert(~report.crossStudyAggregationPerformed);
assert(~report.computationalExecutionEstablished);
end

