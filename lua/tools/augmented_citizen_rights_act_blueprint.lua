local Blueprint = {}

Blueprint.title = "Augmented Citizen Rights Act: Policy Blueprint"
Blueprint.version = "1.0"
Blueprint.status = "advocacy_draft_not_enacted_law"

Blueprint.legislative_findings = {
    "People using assistive, adaptive, neural, or other augmentation-related technologies retain equal dignity and ordinary civil participation rights.",
    "Public and private systems can create avoidable barriers through inaccessible interfaces, arbitrary device restrictions, unnecessary identity gates, and excessive data collection.",
    "Sensitive neural, biometric, device, and telemetry data require strong purpose limitation, data minimization, security, notice, and consent safeguards.",
    "Accessibility, privacy, civil-rights, disability-rights, consumer-protection, and procurement rules provide an immediate foundation for stronger legislative protections.",
}

Blueprint.definitions = {
    augmented_person = "An individual who uses or relies upon an assistive, adaptive, implantable, wearable, neural, or other technology in connection with communication, mobility, perception, health, cognition, or daily functioning.",
    assistive_technology = "Equipment, software, services, or systems used to increase, maintain, or improve functional capability or access.",
    neural_data = "Data generated by, derived from, or used to infer information about nervous-system activity, subject to clear statutory limits and definitions.",
    ordinary_access = "Access to a public or private service without unnecessary identity certification, discrimination, or avoidable accessibility barriers.",
    effective_communication = "Communication that is as effective for a person using an assistive modality as for others, assessed in context.",
}

Blueprint.sections = {
    {
        id = "section_1_equal_access",
        title = "Equal Access and Non-Discrimination",
        requirements = {
            "Prohibit unjustified adverse treatment in covered employment, housing, public accommodation, education, government services, and civic participation based on assistive or augmentation-related technology use.",
            "Prohibit ordinary-access penalties based solely on identity verifiability, self-asserted identity, or absence of unnecessary third-party certification.",
            "Require individualized, evidence-based safety review rather than speculation or stereotypes when access restrictions are proposed.",
        },
        limitations = {
            "Covered entities, defenses, remedies, and evidentiary standards must be specified through enacted text.",
            "This blueprint does not assert that augmentation status is currently a federally recognized quasi-suspect class.",
        },
    },
    {
        id = "section_2_accessibility",
        title = "Accessibility, Effective Communication, and Continuity",
        requirements = {
            "Require accessible communication and reasonable accommodation processes for covered services.",
            "Require supported assistive pathways or equally effective alternatives for core tasks.",
            "Require continuity of core access and authorized task context across supported interface changes.",
            "Require accessible grievance, correction, and review mechanisms.",
        },
        limitations = {
            "Accommodation analysis remains fact-specific and may include statutory defenses such as undue burden or fundamental alteration where applicable.",
        },
    },
    {
        id = "section_3_sensitive_data",
        title = "Neural, Biometric, Device, and Telemetry Data Safeguards",
        requirements = {
            "Require documented purpose limitation, data minimization, retention controls, and accessible privacy notices.",
            "Require explicit, revocable consent for optional sensitive-data processing.",
            "Provide access, correction, deletion, and portability mechanisms where legally and technically appropriate.",
            "Require security controls, breach response, and privacy-preserving audit records.",
        },
        limitations = {
            "Government access, private data practices, health information, employment information, and consumer data may require distinct statutory provisions.",
            "This blueprint does not itself create a categorical warrant rule or universal data-property right.",
        },
    },
    {
        id = "section_4_repair_interoperability",
        title = "Repair, Modification, and Interoperability",
        requirements = {
            "Promote documented repair, maintenance, compatibility, and safe user-controlled configuration pathways.",
            "Require public digital services to avoid unnecessary device lockout and text-only access barriers.",
            "Use open, documented standards in public procurement where feasible, secure, and consistent with accessibility.",
        },
        limitations = {
            "Safety, cybersecurity, medical regulation, warranty, intellectual-property, and contractual concerns require targeted statutory balancing.",
        },
    },
    {
        id = "section_5_enforcement",
        title = "Enforcement, Remedies, and Public Accountability",
        requirements = {
            "Establish an accessible administrative complaint and resolution process.",
            "Authorize qualified public enforcement and, if enacted, define any private right of action precisely.",
            "Provide proportionate remedies, including accessible correction, injunctive relief, documented remediation, and fee-shifting where appropriate.",
            "Require aggregate public reporting that excludes raw neural, biometric, device, location, and identity data.",
        },
        limitations = {
            "Office structure, funding, remedies, preemption, and federalism questions require legislative drafting and constitutional review.",
        },
    },
    {
        id = "section_6_non_preemption_floor",
        title = "Minimum Floor of Protection",
        requirements = {
            "Establish a federal minimum floor while allowing stronger compatible state and local protections unless Congress expressly decides otherwise.",
        },
        limitations = {
            "The scope of preemption should be decided transparently through legislative process; broad preemption can displace stronger local safeguards.",
        },
    },
}

Blueprint.implementation_plan = {
    "Conduct disability-led, augmented-person-led, civil-rights, privacy, consumer-protection, accessibility, technical-security, and public-sector consultation.",
    "Develop accessible public comment materials in multiple modalities.",
    "Commission an evidence review on device interoperability, accessibility barriers, sensitive-data governance, repair barriers, and discrimination patterns.",
    "Pilot privacy-preserving compliance reporting before imposing broad data-collection duties.",
    "Obtain constitutional, statutory, administrative, fiscal, and jurisdiction-specific legal review before introduction.",
}

